impl Key {
    fn def(self) -> &'static KeyDef {
        // KEY_DEFS is generated from the same list as the enum, in the same
        // order, so the variant's discriminant is its row index.
        &KEY_DEFS[self as usize]
    }

    /// The config.toml / configui name for this key (e.g. "LSHIFT").
    pub fn name(self) -> &'static str {
        self.def().name
    }

    /// Win32 virtual-key code (`VK_*`).
    #[cfg_attr(not(windows), allow(dead_code))]
    pub fn win_vk(self) -> u16 {
        self.def().win_vk
    }

    /// macOS keycode / media-key mapping.
    #[cfg_attr(not(target_os = "macos"), allow(dead_code))]
    pub fn mac(self) -> MacKey {
        self.def().mac
    }

    /// Whether the OS this binary was built for can emit this key at all.
    /// Windows can emit the whole vocabulary; macOS has no equivalent for a
    /// few (see `MacKey::Unsupported` rows above).
    pub fn supported_here(self) -> bool {
        if cfg!(target_os = "macos") {
            self.mac() != Unsupported
        } else {
            true
        }
    }

    pub fn is_media(self) -> bool {
        matches!(self, Key::MediaPlayPause | Key::MediaStop | Key::MediaNext | Key::MediaPrev
            | Key::VolumeMute | Key::VolumeDown | Key::VolumeUp)
    }

    /// Looks a name up (case-insensitive, surrounding whitespace ignored)
    /// regardless of whether the current OS can emit it. Use `from_name`
    /// for config parsing; this exists so callers can tell "unknown name"
    /// apart from "known key, unavailable on this OS" in their warnings.
    pub fn lookup(name: &str) -> Option<Key> {
        let upper = name.trim().to_ascii_uppercase();
        KEY_DEFS.iter().find(|d| d.name == upper).map(|d| d.key)
    }

    /// Parses a human-readable key name (case-insensitive) into a `Key`,
    /// accepting only keys the current OS can emit. Returns None for
    /// anything else — the caller is expected to fall back / reject, never
    /// to guess.
    pub fn from_name(name: &str) -> Option<Key> {
        Key::lookup(name).filter(|k| k.supported_here())
    }
}

/// Every name `Key::from_name` accepts (on this OS), in display order —
/// the "basic" category only, i.e. everything except the media keys.
/// Populates configui.html's dropdowns via GET /api/key-options.
pub fn all_key_names() -> Vec<String> {
    KEY_DEFS
        .iter()
        .filter(|d| !d.key.is_media() && d.key.supported_here())
        .map(|d| d.name.to_string())
        .collect()
}

/// (basic names, media names) — the same vocabulary as all_key_names(),
/// just split into the two categories configui.html's key picker offers.
/// Used by configui.rs's GET /api/key-options.
pub fn key_names_grouped() -> (Vec<String>, Vec<String>) {
    let media = KEY_DEFS
        .iter()
        .filter(|d| d.key.is_media() && d.key.supported_here())
        .map(|d| d.name.to_string())
        .collect();
    (all_key_names(), media)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_index_matches_enum_discriminant() {
        for (i, d) in KEY_DEFS.iter().enumerate() {
            assert_eq!(d.key as usize, i, "{} is out of order", d.name);
            assert_eq!(d.key.name(), d.name);
        }
    }

    #[test]
    fn names_and_codes_are_unique() {
        for (i, a) in KEY_DEFS.iter().enumerate() {
            for b in &KEY_DEFS[i + 1..] {
                assert_ne!(a.name, b.name);
                assert_ne!(a.win_vk, b.win_vk, "{} and {} share a VK", a.name, b.name);
                if a.mac != Unsupported {
                    assert_ne!(a.mac, b.mac, "{} and {} share a mac code", a.name, b.name);
                }
            }
        }
    }

    #[test]
    fn digits_and_letters_round_trip() {
        for c in ('0'..='9').chain('A'..='Z') {
            let key = Key::from_name(&c.to_string()).unwrap();
            assert_eq!(key.name(), c.to_string());
            // Windows VK for digits/letters is the ASCII code.
            assert_eq!(key.win_vk(), c as u16);
        }
    }

    #[test]
    fn function_keys_round_trip_and_are_bounded() {
        for n in 1..=24 {
            let name = format!("F{n}");
            let key = Key::lookup(&name).unwrap();
            assert_eq!(key.name(), name);
            assert_eq!(key.win_vk(), 0x70 + n - 1);
        }
        assert_eq!(Key::from_name("F0"), None);
        assert_eq!(Key::from_name("F25"), None);
    }

    #[test]
    fn every_supported_name_round_trips() {
        let (basic, media) = key_names_grouped();
        assert!(basic.len() > 50);
        for name in basic.iter().chain(&media) {
            let key = Key::from_name(name).unwrap_or_else(|| panic!("{name} did not round-trip"));
            assert_eq!(key.name(), name);
        }
        for name in &media {
            assert!(!basic.contains(name));
        }
    }

    #[test]
    fn case_insensitive_and_unknown_names_rejected() {
        assert_eq!(Key::from_name("left"), Some(Key::Left));
        assert_eq!(Key::from_name(" f1 "), Key::from_name("F1"));
        assert_eq!(Key::from_name("NOT_A_KEY"), None);
        assert_eq!(Key::from_name(""), None);
    }

    #[test]
    fn unsupported_keys_are_known_but_rejected_on_macos() {
        // Known everywhere...
        assert_eq!(Key::lookup("F24"), Some(Key::F24));
        assert_eq!(Key::lookup("MEDIA_STOP"), Some(Key::MediaStop));
        // ...but only emittable where the OS has a code for them.
        let expect = !cfg!(target_os = "macos");
        assert_eq!(Key::from_name("F24").is_some(), expect);
        assert_eq!(Key::from_name("MEDIA_STOP").is_some(), expect);
        assert_eq!(all_key_names().contains(&"F24".to_string()), expect);
    }

    // The raw VK numbers in KEY_DEFS must agree with the `windows` crate's
    // own constants — this is the one place the table can be checked
    // against the real SDK header values.
    #[cfg(windows)]
    #[test]
    fn win_vk_table_matches_windows_crate_constants() {
        use windows::Win32::UI::Input::KeyboardAndMouse::*;
        let expect: &[(Key, VIRTUAL_KEY)] = &[
            (Key::Digit0, VK_0),
            (Key::A, VK_A),
            (Key::F1, VK_F1),
            (Key::F24, VK_F24),
            (Key::Left, VK_LEFT),
            (Key::Up, VK_UP),
            (Key::Right, VK_RIGHT),
            (Key::Down, VK_DOWN),
            (Key::Space, VK_SPACE),
            (Key::Enter, VK_RETURN),
            (Key::Tab, VK_TAB),
            (Key::Escape, VK_ESCAPE),
            (Key::Backspace, VK_BACK),
            (Key::LShift, VK_LSHIFT),
            (Key::RShift, VK_RSHIFT),
            (Key::LCtrl, VK_LCONTROL),
            (Key::RCtrl, VK_RCONTROL),
            (Key::LAlt, VK_LMENU),
            (Key::RAlt, VK_RMENU),
            (Key::LCmd, VK_LWIN),
            (Key::RCmd, VK_RWIN),
            (Key::Home, VK_HOME),
            (Key::End, VK_END),
            (Key::PageUp, VK_PRIOR),
            (Key::PageDown, VK_NEXT),
            (Key::Insert, VK_INSERT),
            (Key::Delete, VK_DELETE),
            (Key::MediaPlayPause, VK_MEDIA_PLAY_PAUSE),
            (Key::MediaStop, VK_MEDIA_STOP),
            (Key::MediaNext, VK_MEDIA_NEXT_TRACK),
            (Key::MediaPrev, VK_MEDIA_PREV_TRACK),
            (Key::VolumeMute, VK_VOLUME_MUTE),
            (Key::VolumeDown, VK_VOLUME_DOWN),
            (Key::VolumeUp, VK_VOLUME_UP),
        ];
        for (key, vk) in expect {
            assert_eq!(key.win_vk(), vk.0, "{}", key.name());
        }
    }
}
