// Platform-neutral key identity + the human-readable key-name vocabulary
// used by config.toml and the `configui` web page.
//
// Before the macOS port this role was played directly by the Win32
// `VIRTUAL_KEY` newtype (see the old vkname.rs): every keymap, config struct
// and held-key tracker stored raw VK codes, and the name<->VK tables lived
// in two parallel arrays. That works on exactly one OS. `Key` is the same
// closed vocabulary — deliberately NOT "any code the user types", so every
// name that round-trips through here either produces a real, intentional
// key or a caught error, never a silently wrong/unmapped value — expressed
// as a plain enum, with each variant's per-OS code carried alongside it in
// ONE table (KEY_DEFS, generated by the `define_keys!` macro below from a
// single list) so the name, the Windows VK and the macOS virtual keycode
// can never drift apart.
//
// `all_key_names()` remains the single source of truth for what
// configui.html's <select> options are allowed to contain (fetched from the
// running driver via GET /api/key-options rather than duplicated in the
// HTML, so the two can never drift apart) — now filtered to the keys the
// CURRENT OS can actually emit (see `Key::supported_here`).

/// What a `Key` becomes on macOS: a CoreGraphics virtual keycode
/// (`kVK_*`, posted via CGEventPost), an `NX_KEYTYPE_*` "system-defined"
/// media key (posted via NSEvent), or nothing at all — macOS has no
/// equivalent for a handful of Windows VKs (F21-F24, MEDIA_STOP).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MacKey {
    Code(u16),
    Media(u8),
    Unsupported,
}

pub struct KeyDef {
    pub key: Key,
    pub name: &'static str,
    /// Win32 virtual-key code (`VK_*`). Stored as the raw u16 rather than
    /// the `windows` crate's `VIRTUAL_KEY` so this table compiles on every
    /// OS; platform/windows.rs wraps it back into `VIRTUAL_KEY` at the
    /// SendInput call site.
    pub win_vk: u16,
    pub mac: MacKey,
}

// One row per key: `Variant => "NAME", win: VK, mac: MacKey;`. Rows are in
// configui display order within each group (see `key_names_grouped`), so
// reordering rows here reorders the web page's dropdowns.
macro_rules! define_keys {
    ($( $variant:ident => $name:literal, win: $vk:expr, mac: $mac:expr; )*) => {
        #[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
        pub enum Key {
            $( $variant, )*
        }

        pub const KEY_DEFS: &[KeyDef] = &[
            $( KeyDef { key: Key::$variant, name: $name, win_vk: $vk, mac: $mac }, )*
        ];
    };
}

